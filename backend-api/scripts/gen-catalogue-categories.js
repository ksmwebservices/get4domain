#!/usr/bin/env node
'use strict';
/**
 * Writes src/directory/core/catalogue-categories.ts from the catalogue sheet (prisma/seed/pack-engine/CATEGORY_MASTER_V3_ADMIN_REGISTRATION.csv): the id, name, family and primary pack of every category.
 * Offline, no database, no environment. A test (test/wave2-catalogue-categories.spec.ts) fails when the checked-in file and the sheet disagree, so run this after the sheet changes:
 *
 *   node scripts/gen-catalogue-categories.js            writes the file
 *   node scripts/gen-catalogue-categories.js --check    exits 1 when the file is out of date, writes nothing
 *
 * Needs `npm run build` first (it uses the compiled sheet parser).
 */
const fs = require('fs');
const path = require('path');
const BACKEND = path.resolve(__dirname, '..');
const OUT = path.join(BACKEND, 'src/directory/core/catalogue-categories.ts');
const { parseCsv } = require(path.join(BACKEND, 'dist/src/v3-packs/core/pack-core'));

const rows = parseCsv(fs.readFileSync(path.join(BACKEND, 'prisma/seed/pack-engine/CATEGORY_MASTER_V3_ADMIN_REGISTRATION.csv'), 'utf8'));
if (!rows.length || ['id', 'name', 'family', 'primary_pack'].some((k) => !(k in rows[0]))) { console.error('The sheet has no id, name, family or primary_pack column.'); process.exit(2); }
const items = rows.filter((r) => r.id && r.id.trim()).map((r) => ({ id: r.id.trim(), name: r.name.trim(), family: r.family.trim(), pack: r.primary_pack.trim() }));

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const text = `// GENERATED by scripts/gen-catalogue-categories.js from prisma/seed/pack-engine/CATEGORY_MASTER_V3_ADMIN_REGISTRATION.csv. Do not edit by hand: change the sheet and run the script.
// test/wave2-catalogue-categories.spec.ts fails when this file and the sheet disagree.
export interface CatalogueCategory { id: string; name: string; family: string; pack: string }

export const CATALOGUE_CATEGORIES: readonly CatalogueCategory[] = [
${items.map((c) => `  { id: ${q(c.id)}, name: ${q(c.name)}, family: ${q(c.family)}, pack: ${q(c.pack)} },`).join('\n')}
];
`;
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== text) { console.error('src/directory/core/catalogue-categories.ts is out of date: run node scripts/gen-catalogue-categories.js'); process.exit(1); }
  console.log(`up to date (${items.length} categories)`);
} else { fs.writeFileSync(OUT, text); console.log(`wrote ${OUT} (${items.length} categories)`); }
