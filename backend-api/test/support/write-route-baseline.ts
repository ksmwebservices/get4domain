/** Regenerates test/baselines/route-classification.json from the current code:  npm run routes:baseline
 *  Review the git diff of that file: every added or re-classified route is a security decision. */
import * as fs from 'fs';
import * as path from 'path';
import { scanRoutes, violatesStaffPath } from './route-scan';

const srcDir = path.resolve(__dirname, '../../src');
const routes = scanRoutes(srcDir);
const out = {
  note: 'Generated by test/support/write-route-baseline.ts. Reviewed classification of every HTTP route. Do not edit by hand.',
  summary: {
    total: routes.length,
    public: routes.filter((r) => r.cls === 'public').length,
    admin: routes.filter((r) => r.cls === 'admin').length,
    authenticated: routes.filter((r) => r.cls === 'authenticated').length,
  },
  routes: routes.map((r) => ({ ...r, staffPathNotAdminGuarded: violatesStaffPath(r) || undefined })),
};
const file = path.resolve(__dirname, '../baselines/route-classification.json');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
console.log(`wrote ${path.relative(process.cwd(), file)}: ${JSON.stringify(out.summary)}`);
