#!/bin/sh
# Writes /etc/nginx/snippets/cloudflare-realip.conf from Cloudflare's published address lists, so the real visitor address (CF-Connecting-IP) is trusted
# ONLY when the connection really comes from Cloudflare. Run on the server host as root, then: nginx -t && systemctl reload nginx. Repeat now and then (the lists change rarely).
# The address lists are fetched at run time from Cloudflare's own pages; none is copied into this repository, so it can never go stale here.
set -eu
OUT="${1:-/etc/nginx/snippets/cloudflare-realip.conf}"
TMP="$(mktemp)"
V4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
V6="$(curl -fsS https://www.cloudflare.com/ips-v6)"
{
  echo "# generated by update-cloudflare-ips.sh; do not edit by hand"
  for cidr in $V4 $V6; do
    case "$cidr" in
      *[!0-9a-fA-F:./]*) echo "unexpected text in the Cloudflare list; nothing written" >&2; rm -f "$TMP"; exit 1 ;;
    esac
    echo "set_real_ip_from ${cidr};"
  done
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} > "$TMP"
# refuse an empty or truncated result
[ "$(grep -c '^set_real_ip_from ' "$TMP")" -ge 10 ] || { echo "too few address ranges; nothing written" >&2; rm -f "$TMP"; exit 1; }
[ -f "$OUT" ] && cp -p "$OUT" "$OUT.bak-$(date +%Y%m%d%H%M%S)"
install -m 644 "$TMP" "$OUT"
rm -f "$TMP"
echo "wrote $OUT"
