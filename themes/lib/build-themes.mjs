// The Standard theme build. Each Standard theme is a SELF-CONTAINED package (the package format has no cross-package imports), so the shared parts are
// COPIED into every theme by this build:
//   themes/source/shared/        css/core.css, motion.css (the Standard extras; the kit itself is themes/shared/motion-kit.css), print.css and the shared templates (partials start with "_")
//   themes/source/<theme-id>/    theme.mjs (config), theme.css, templates/ (own pages and partials, which beat the shared ones), presets.mjs
//   themes/library/<theme-id>/   the OUTPUT (committed): theme.json, templates/, css/, presets/
// `node themes/cli.mjs build-themes` writes the output, `--check` fails when the committed files differ from what the sources produce.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { derivePalette, paletteFindings } from './preset.mjs';
import { THEME_TEXT } from './preset-build.mjs';
import { FAMILIES, CATEGORIES } from './categories.mjs';
import { readThemeDir } from './pack.mjs';
import { LIBRARY_DIR } from './theme.mjs';

export const SOURCE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'source');
/** The premium motion kit: one file, copied byte for byte into every theme package (css/motion.css) between these markers. */
export const MOTION_KIT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'shared', 'motion-kit.css');
export const MOTION_KIT_BEGIN = '/* shared:motion-kit:begin */\n';
export const MOTION_KIT_END = '/* shared:motion-kit:end */\n';
/** css/motion.css = the kit between markers, followed by whatever the theme adds of its own. */
export const withMotionKit = (own = '') => {
  const kit = fs.readFileSync(MOTION_KIT_FILE, 'utf8');
  return `${MOTION_KIT_BEGIN}${kit}${kit.endsWith('\n') ? '' : '\n'}${MOTION_KIT_END}${own}`;
};
const SERIF = new Set(['Playfair Display', 'Lora', 'Merriweather']);
const MAX_INCLUDE_DEPTH = 6;

const readIf = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null);

export function standardThemeIds(root = SOURCE_ROOT) {
  if (!fs.existsSync(root)) return [];
  return fs.readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory() && fs.existsSync(path.join(root, d.name, 'theme.mjs'))).map((d) => d.name).sort();
}

async function loadConfig(id, root) {
  const file = path.join(root, id, 'theme.mjs');
  const mod = await import(`${pathToFileURL(file).href}?t=${fs.statSync(file).mtimeMs}`);
  const cfg = mod.default;
  if (!cfg || cfg.id !== id) throw new Error(`source/${id}/theme.mjs must export a config whose id is "${id}"`);
  return cfg;
}

function partial(name, id, root) {
  return readIf(path.join(root, id, 'templates', `_${name}.html`)) ?? readIf(path.join(root, 'shared', 'templates', `_${name}.html`));
}

function expand(html, id, root, depth = 0) {
  if (depth > MAX_INCLUDE_DEPTH) throw new Error(`theme ${id}: partials include each other too deep (a loop?)`);
  return html.replace(/\{\{>\s*([a-z0-9-]+)\s*\}\}/g, (_m, name) => {
    const part = partial(name, id, root);
    if (part === null) throw new Error(`theme ${id}: unknown partial "${name}" (looked for source/${id}/templates/_${name}.html and source/shared/templates/_${name}.html)`);
    return expand(part.replace(/\n$/, ''), id, root, depth + 1);
  });
}

function pages(id, root) {
  const names = new Map();
  for (const dir of [path.join(root, 'shared', 'templates'), path.join(root, id, 'templates')]) {
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) if (f.endsWith('.html') && !f.startsWith('_')) names.set(f.slice(0, -5), path.join(dir, f));
  }
  return names;
}

function tokensCss(cfg) {
  const L = derivePalette('light', cfg.palette.light);
  const D = derivePalette('dark', cfg.palette.dark);
  const stack = (name) => `'${name}', 'Noto Sans Tamil', 'Nirmala UI', 'Latha', ${SERIF.has(name) ? 'serif' : 'system-ui, sans-serif'}`;
  return `/* Design tokens. Generated by themes/lib/build-themes.mjs from source/${cfg.id}/theme.mjs: do not edit by hand.
   The category preset (or the vendor's accent) supplies the --g4d-pal-* variables; the value after the comma is this theme's own default. */
.g4d-theme {
  --g4d-primary: var(--g4d-pal-primary, ${L.primary});
  --g4d-primary-contrast: var(--g4d-pal-primary-contrast, ${L.primaryContrast});
  --g4d-accent: var(--g4d-pal-accent, ${L.accent});
  --g4d-bg: var(--g4d-pal-bg, ${L.bg});
  --g4d-surface: var(--g4d-pal-surface, ${L.surface});
  --g4d-text: ${THEME_TEXT.text};
  --g4d-muted: ${THEME_TEXT.muted};
  --g4d-border: var(--g4d-pal-border, ${L.border});
  --g4d-radius: ${cfg.radius ?? '12px'};
  --g4d-font-fallback: 'Noto Sans Tamil', 'Nirmala UI', 'Latha', system-ui, sans-serif;
  --g4d-font-heading: ${stack(cfg.fonts.heading)};
  --g4d-font-body: ${stack(cfg.fonts.body)};
  --g4d-touch: 44px;
}

@media (prefers-color-scheme: dark) {
  .g4d-theme {
    --g4d-primary: var(--g4d-pal-primary-d, ${D.primary});
    --g4d-primary-contrast: var(--g4d-pal-primary-contrast-d, ${D.primaryContrast});
    --g4d-accent: var(--g4d-pal-accent-d, ${D.accent});
    --g4d-bg: var(--g4d-pal-bg-d, ${D.bg});
    --g4d-surface: var(--g4d-pal-surface-d, ${D.surface});
    --g4d-text: ${THEME_TEXT.textDark};
    --g4d-muted: ${THEME_TEXT.mutedDark};
    --g4d-border: var(--g4d-pal-border-d, ${D.border});
  }
}
`;
}

/** @returns {Promise<{files:Record<string,Buffer>, config:object}>} the whole self-contained package for one theme */
export async function buildThemeFiles(id, { root = SOURCE_ROOT } = {}) {
  const cfg = await loadConfig(id, root);
  const problems = paletteFindings(cfg.palette, THEME_TEXT);
  if (problems.length) throw new Error(`theme ${id}: its own palette fails contrast: ${problems.join('; ')}`);
  const files = {};
  const put = (p, text) => { files[p] = Buffer.from(text, 'utf8'); };

  for (const [name, file] of pages(id, root)) put(`templates/${name}.html`, expand(fs.readFileSync(file, 'utf8').replace(/\n$/, ''), id, root) + '\n');

  const core = fs.readFileSync(path.join(root, 'shared/css/core.css'), 'utf8');
  put('css/base.css', `/* shared:core:begin */\n${core}/* shared:core:end */\n${readIf(path.join(root, id, 'theme.css')) ?? ''}`);
  put('css/tokens.css', tokensCss(cfg));
  put('css/motion.css', withMotionKit(`${fs.readFileSync(path.join(root, 'shared/css/motion.css'), 'utf8')}${readIf(path.join(root, id, 'motion.css')) ?? ''}`));
  put('css/print.css', fs.readFileSync(path.join(root, 'shared/css/print.css'), 'utf8'));

  const presets = cfg.presets ?? {};
  for (const [cat, preset] of Object.entries(presets)) put(`presets/${cat}.json`, `${JSON.stringify(preset, null, 2)}\n`);

  const families = cfg.families;
  const fonts = [...new Set([cfg.fonts.heading, cfg.fonts.body, ...Object.values(presets).flatMap((p) => [p.fonts.heading, p.fonts.body]), 'Noto Sans Tamil'])];
  const manifest = {
    id: cfg.id,
    version: cfg.version ?? 1,
    name: cfg.name,
    description: cfg.description,
    author: 'Get4Domain',
    tier: cfg.tier ?? 'Standard',
    tracks: cfg.tracks,
    families,
    categories: CATEGORIES.filter((c) => families.includes(c.family)).map((c) => c.id),
    layoutVariantRules: Object.fromEntries(families.map((f) => [f, FAMILIES[f].variant.id])),
    motion: { default: 'Low', variantDefaults: {} },
    settingsSchema: { accent: true, fonts: true, logo: true, sectionOrder: true, sectionVisibility: true, motionIntensity: true },
    fonts,
  };
  put('theme.json', `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, config: cfg };
}
export const buildTheme = buildThemeFiles;

export async function buildAll({ root = SOURCE_ROOT } = {}) {
  const out = {};
  for (const id of standardThemeIds(root)) out[id] = (await buildThemeFiles(id, { root })).files;
  return out;
}

/** @returns {Promise<string[]>} one sentence per difference between what the sources produce and the committed theme folders */
export async function checkBuilt({ root = SOURCE_ROOT, libraryDir = LIBRARY_DIR } = {}) {
  const diffs = [];
  const built = await buildAll({ root });
  for (const [id, files] of Object.entries(built)) {
    const dir = path.join(libraryDir, id);
    const actual = fs.existsSync(dir) ? readThemeDir(dir) : {};
    for (const [p, data] of Object.entries(files)) {
      if (!actual[p]) diffs.push(`${id}/${p}: missing from the committed theme`);
      else if (!actual[p].equals(data)) diffs.push(`${id}/${p}: differs from what the sources produce`);
    }
    for (const p of Object.keys(actual)) if (!files[p]) diffs.push(`${id}/${p}: committed but not produced by the build`);
  }
  return diffs;
}

export async function writeBuilt({ root = SOURCE_ROOT, libraryDir = LIBRARY_DIR } = {}) {
  const built = await buildAll({ root });
  for (const [id, files] of Object.entries(built)) {
    const dir = path.join(libraryDir, id);
    if (fs.existsSync(dir)) for (const p of Object.keys(readThemeDir(dir))) if (!files[p]) fs.rmSync(path.join(dir, p));
    for (const [p, data] of Object.entries(files)) { fs.mkdirSync(path.dirname(path.join(dir, p)), { recursive: true }); fs.writeFileSync(path.join(dir, p), data); }
  }
  return Object.keys(built);
}
